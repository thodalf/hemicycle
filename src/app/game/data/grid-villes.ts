import type { RegionCode } from './departements';

/*
 * Base de données du mini-jeu « Grille des villes » (façon Metrodoku) :
 * une grille 3×3 où chaque case croise deux critères (région, littoral,
 * frontière, préfecture, population, fleuve…) et attend une commune qui
 * satisfait les deux.
 *
 * France métropolitaine uniquement. Toutes les préfectures des 96 départements
 * sont présentes, plus les plus grandes communes non préfectures et une
 * sélection de petites villes connues (> ~3 000 hab.).
 *
 * Populations : populations municipales INSEE récentes (années 2020),
 * arrondies au millier. Régions : découpage de 2016.
 * Le drapeau « border » se déduit du département (frontière terrestre avec
 * un pays étranger) ; « coast », « prefecture » et « regionCapital » sont
 * saisis via la chaîne de drapeaux du helper `v` :
 *   c = littoral maritime, p = préfecture, r = chef-lieu de région.
 * Le fleuve n’est renseigné que lorsqu’il traverse (ou longe directement)
 * la commune de façon certaine.
 */

export type River = 'Seine' | 'Loire' | 'Rhône' | 'Garonne' | 'Rhin' | 'Moselle' | 'Dordogne' | 'Saône' | 'Marne' | 'Oise' | 'Meuse' | 'Allier' | 'Lot' | 'Vienne' | 'Isère' | 'Somme' | 'Charente' | 'Durance' | 'Escaut';

export interface Ville {
  name: string;          // nom officiel avec accents et tirets (ex. 'Saint-Étienne', 'Le Havre', 'Aix-en-Provence')
  dep: string;           // code du département ('01'…'95', '2A', '2B')
  region: RegionCode;    // 'ARA' | 'BFC' | 'BRE' | 'CVL' | 'COR' | 'GES' | 'HDF' | 'IDF' | 'NOR' | 'NAQ' | 'OCC' | 'PDL' | 'PAC'
  pop: number;           // population municipale récente (INSEE, années 2020), arrondie au millier (ex. 518000)
  coast: boolean;        // la commune est sur le littoral maritime (mer ou océan, pas un lac)
  border: boolean;       // le département de la commune touche un pays étranger (frontière terrestre)
  prefecture: boolean;   // la commune est préfecture de son département
  regionCapital: boolean;// la commune est chef-lieu de région
  river?: River;         // fleuve ou grande rivière qui traverse la commune, si c'est l'un de la liste
}

/** Départements ayant une frontière terrestre avec un pays étranger (la Corse n’en a pas) */
const BORDER_DEPS = new Set([
  '01', '02', '04', '05', '06', '08', '09', '25', '31', '39', '54',
  '55', '57', '59', '64', '65', '66', '67', '68', '73', '74', '90',
]);

const v = (name: string, dep: string, region: RegionCode, pop: number, flags = '', river?: River): Ville => ({
  name, dep, region, pop,
  coast: flags.includes('c'),
  border: BORDER_DEPS.has(dep),
  prefecture: flags.includes('p'),
  regionCapital: flags.includes('r'),
  ...(river ? { river } : {}),
});

