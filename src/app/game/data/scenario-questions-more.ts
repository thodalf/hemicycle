/* Propositions qui déclenchent des scénarios (voir scenario-questions.ts) */

const st = (stat: StatKey, delta: number): Effect => ({ kind: 'stat', stat, delta });
const seg = (segment: Segment, delta: number): Effect => ({ kind: 'segment', segment, delta });
const flag = (key: string): Effect => ({ kind: 'flag', key, value: true });

/** Démarrer une crise au long cours (et marquer la question comme posée, et l'événement « gate » comme vu) */
const crisis = (arc: CrisisArcId, done: string, gauge = 0, risk = 0): Effect[] => [
  { kind: 'crisis', arc, start: true, gauge, risk }, flag(`sq_arc_${arc}`), flag(done),
];
/** Démarrer une saga */
const saga = (id: string): Effect[] => [{ kind: 'saga', start: id }, flag(`sq_arc_${id}`)];

const arcOk = (d: GameState, arc: CrisisArcId, done: string, rank: number): boolean =>
  arcFree(d, arc) && !d.player.flags[done] && rankAtLeast(d, rank);
const sagaOk = (d: GameState, id: string, rank: number): boolean =>
  sagaFree(d, id) && !(d.sagasDone ?? []).includes(id) && !d.player.flags[`sq_arc_${id}`] && rankAtLeast(d, rank);
/** Un projet local de ce type peut-il être lancé ? */
const projectOk = (d: GameState, id: string): boolean => {
  const projects = d.territory?.projects ?? [];
  return projects.filter(p => !p.finished).length < 2 && !projects.some(p => p.id === id) && !d.player.flags[`sq_arc_${id}`];
};

const a = (id: string, label: string, effects: Effect[], reply: string, replyTu: string, hint?: string): ScenarioAnswer =>
  ({ id, label, effects, reply, replyTu, ...(hint ? { hint } : {}) });

