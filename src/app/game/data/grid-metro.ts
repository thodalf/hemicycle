/*
 * Metrodoku — base de données des stations du métro parisien (réseau 2025).
 * Chaque station n'apparaît qu'une fois, avec toutes ses lignes de métro
 * et les lignes de RER en correspondance officielle dans le même pôle.
 * Inclut les prolongements récents : 4 (Bagneux – Lucie Aubrac),
 * 11 (Rosny-Bois-Perrier), 12 (Mairie d'Aubervilliers), 14 (Saint-Denis – Pleyel / Aéroport d'Orly).
 */

export type Line = '1' | '2' | '3' | '3bis' | '4' | '5' | '6' | '7' | '7bis' | '8' | '9' | '10' | '11' | '12' | '13' | '14';
export type Rer = 'A' | 'B' | 'C' | 'D' | 'E';

export interface Station {
  name: string;   // nom officiel avec accents
  lines: Line[];  // toutes les lignes de métro qui desservent la station
  rer: Rer[];     // lignes de RER en correspondance directe dans le même pôle
}

/** s('Châtelet', '1 4 7 11 14', 'ABD') */
const s = (name: string, lines: string, rer = ''): Station => ({
  name,
  lines: lines.split(' ') as Line[],
  rer: rer.split('').filter(Boolean) as Rer[],
});

